function linkRelated(skill: Skill, _index: number, all: Skill[]): Skill {
  const sameTopic = all.filter((o) => o.id !== skill.id && o.topic === skill.topic)
  const sameGrade = sameTopic.filter((o) => o.grade === skill.grade)
  const ids = [...sameGrade, ...sameTopic.filter((o) => o.grade !== skill.grade)].slice(0, 4).map((o) => o.id)
  return { ...skill, related: ids }
}

const grades: GradeId[] = ['k', '1', '2', '3', '4', '5', '6', '7', '8']

export function maxBatch(): number {
  const raw = Number(process.env.MAX_BATCH || '3')
  if (!Number.isFinite(raw) || raw < 1) return 3
  return Math.min(3, Math.floor(raw))
}

export function publishedSkills(): Skill[] {
  const max = maxBatch()
  return SKILLS.filter((s) => s.batch <= max)
}

export function skillPath(skill: Skill): string {
  return `/grade-${skill.grade}/${skill.subject}/${skill.topic}/${skill.slug}/`
}

export function byId(id: string): Skill | undefined {
  return SKILLS.find((s) => s.id === id)
}

export function gradesWithSkills(): GradeId[] {
  const have = new Set(publishedSkills().map((s) => s.grade))
  return grades.filter((g) => have.has(g))
}

/** Phrase for the grades actually released at the current MAX_BATCH, e.g. "grades 1 through 3". */
export function formatGradeRange(ids: GradeId[]): string {
  const ordered = grades.filter((g) => ids.includes(g))
  if (ordered.length === 0) return 'the grades now on the site'
  const label = (g: GradeId) => (g === 'k' ? 'kindergarten' : `grade ${g}`)
  if (ordered.length === 1) return label(ordered[0])
  const first = ordered[0]
  const last = ordered[ordered.length - 1]
  const span = grades.indexOf(last) - grades.indexOf(first) + 1
  if (ordered.length === span) {
    if (first === 'k') return `kindergarten through grade ${last}`
    return `grades ${first} through ${last}`
  }
  const names = ordered.map(label)
  if (names.length === 2) return `${names[0]} and ${names[1]}`
  return `${names.slice(0, -1).join(', ')}, and ${names[names.length - 1]}`
}

export function releasedGradeRange(): string {
  return formatGradeRange(gradesWithSkills())
}

export function subjectsFor(grade: GradeId): string[] {
  return [...new Set(publishedSkills().filter((s) => s.grade === grade).map((s) => s.subject))]
}

export function topicsFor(grade: GradeId, subject: string): { topic: string; label: string }[] {
  const map = new Map<string, string>()
  for (const s of publishedSkills()) {
    if (s.grade === grade && s.subject === subject) map.set(s.topic, s.topicLabel)
  }
  return [...map.entries()].map(([topic, label]) => ({ topic, label }))
}

export function skillsFor(grade: GradeId, subject: string, topic: string): Skill[] {
  return publishedSkills().filter((s) => s.grade === grade && s.subject === subject && s.topic === topic)
}

export function pdfBase(): string {
  const raw = process.env.PDF_BASE_URL || '/pdf/'
  return raw.endsWith('/') ? raw : `${raw}/`
}

export function pdfRel(skill: Skill, level: string): string {
  return `grade-${skill.grade}/${skill.subject}/${skill.topic}/${skill.slug}/${level}.pdf`
}

export function pdfHref(skill: Skill, level: string): string {
  return `${pdfBase()}${pdfRel(skill, level)}`
}
